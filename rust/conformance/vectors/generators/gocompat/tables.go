// canonicalName copies regexp/syntax.canonicalName, which is unexported.
func canonicalName(name string) string {
	var b []byte
	first := true
	for i := range len(name) {
		c := name[i]
		switch {
		case c == '_' || c == '-' || c == ' ':
			c = ' '
		case first:
			if 'a' <= c && c <= 'z' {
				c -= 'a' - 'A'
			}
			first = false
		default:
			if 'A' <= c && c <= 'Z' {
				c += 'a' - 'A'
			}
		}
		if c == ' ' {
			continue
		}
		b = append(b, c)
	}
	return string(b)
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}

func writeRangeTable(b *bytes.Buffer, t *unicode.RangeTable) {
	b.WriteString("&[")
	for _, r := range t.R16 {
		fmt.Fprintf(b, "(%#x,%#x,%d),", r.Lo, r.Hi, r.Stride)
	}
	for _, r := range t.R32 {
		fmt.Fprintf(b, "(%#x,%#x,%d),", r.Lo, r.Hi, r.Stride)
	}
	b.WriteString("]")
}

func writeTableMap(b *bytes.Buffer, name string, m map[string]*unicode.RangeTable) {
	fmt.Fprintf(b, "pub static %s: &[(&str, RangeTable)] = &[\n", name)
	for _, k := range sortedKeys(m) {
		fmt.Fprintf(b, "(%q, ", k)
		writeRangeTable(b, m[k])
		b.WriteString("),\n")
	}
	b.WriteString("];\n\n")
}

// writeUnicodeTables writes the frozen table module. The tables come from the
// Go toolchain that runs this generator, so they follow its Unicode version.
func writeUnicodeTables(path string) {
	var b bytes.Buffer
	b.WriteString("// Code generated by rust/conformance/vectors/generators/gocompat; DO NOT EDIT.\n\n")
	b.WriteString("#![allow(clippy::unreadable_literal)]\n\n")
	b.WriteString("/// Sorted `(lo, hi, stride)` runs, the merged form of a Go `unicode.RangeTable`.\n")
	b.WriteString("pub type RangeTable = &'static [(u32, u32, u32)];\n\n")
	fmt.Fprintf(&b, "/// The Go toolchain the tables were generated from.\npub const GO_VERSION: &str = %q;\n", runtime.Version())
	fmt.Fprintf(&b, "/// `unicode.Version` of that toolchain.\npub const UNICODE_VERSION: &str = %q;\n\n", unicode.Version)

	b.WriteString("/// `unicode.CaseRanges` as `(lo, hi, [upper, lower, title])`.\n")
	b.WriteString("pub static CASE_RANGES: &[(u32, u32, [i32; 3])] = &[\n")
	for _, c := range unicode.CaseRanges {
		fmt.Fprintf(&b, "(%#x,%#x,[%d,%d,%d]),\n", c.Lo, c.Hi, c.Delta[0], c.Delta[1], c.Delta[2])
	}
	b.WriteString("];\n\n")

	b.WriteString("/// Runes whose `unicode.SimpleFold` differs from the lower-else-upper default.\n")
	b.WriteString("pub static CASE_ORBIT: &[(u32, u32)] = &[\n")
	for r := rune(0); r <= unicode.MaxRune; r++ {
		def := unicode.ToLower(r)
		if def == r {
			def = unicode.ToUpper(r)
		}
		if f := unicode.SimpleFold(r); f != def {
			fmt.Fprintf(&b, "(%#x,%#x),\n", r, f)
		}
	}
	b.WriteString("];\n\n")

	writeTableMap(&b, "CATEGORIES", unicode.Categories)
	writeTableMap(&b, "SCRIPTS", unicode.Scripts)
	writeTableMap(&b, "FOLD_CATEGORY", unicode.FoldCategory)
	writeTableMap(&b, "FOLD_SCRIPT", unicode.FoldScript)

	aliases := map[string]string{}
	for name, actual := range unicode.CategoryAliases {
		aliases[canonicalName(name)] = actual
	}
	b.WriteString("/// `unicode.CategoryAliases` with `regexp/syntax` canonical keys, sorted by key.\n")
	b.WriteString("pub static CATEGORY_ALIASES: &[(&str, &str)] = &[\n")
	for _, k := range sortedKeys(aliases) {
		fmt.Fprintf(&b, "(%q, %q),\n", k, aliases[k])
	}
	b.WriteString("];\n\n")

	b.WriteString("pub static WHITE_SPACE: RangeTable = ")
	writeRangeTable(&b, unicode.White_Space)
	b.WriteString(";\n")

	if err := os.WriteFile(path, b.Bytes(), 0o644); err != nil {
		panic(err)
	}
}

type unicodeVector struct {
	Meta
	RuneMapsSHA256    string `json:"rune_maps_sha256"`
	PredicatesSHA256  string `json:"predicates_sha256"`
	StringMapsSHA256  string `json:"string_maps_sha256"`
	FoldClosureSHA256 string `json:"fold_closure_sha256"`
}

func le32(h interface{ Write([]byte) (int, error) }, vs ...int32) {
	var buf [4]byte
	for _, v := range vs {
		binary.LittleEndian.PutUint32(buf[:], uint32(v))
		h.Write(buf[:])
	}
}

// genUnicode hashes the behavior of every rune, so the crate can be checked
// exhaustively without committing a table that would only be compared to itself.
func genUnicode() unicodeVector {
	maps := sha256.New()
	preds := sha256.New()
	strs := sha256.New()
	fold := sha256.New()
	for r := rune(0); r <= unicode.MaxRune; r++ {
		le32(maps, r, unicode.ToLower(r), unicode.ToUpper(r), unicode.ToTitle(r), unicode.SimpleFold(r))
		var bits int32
		for i, p := range []func(rune) bool{
			unicode.IsLetter, unicode.IsDigit, unicode.IsNumber, unicode.IsUpper, unicode.IsLower,
			unicode.IsTitle, unicode.IsSpace, unicode.IsPunct, unicode.IsSymbol, unicode.IsMark,
			unicode.IsControl, unicode.IsPrint, unicode.IsGraphic,
		} {
			if p(r) {
				bits |= 1 << i
			}
		}
		le32(preds, bits)
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		s := string(r)
		strs.Write([]byte(strings.ToLower(s)))
		strs.Write([]byte{0})
		strs.Write([]byte(strings.ToUpper(s)))
		strs.Write([]byte{0})
		strs.Write([]byte(strings.TrimSpace("a" + s + "b")))
		strs.Write([]byte{0})
		strs.Write([]byte(strings.TrimSpace(s)))
		strs.Write([]byte{0})
		le32(strs, int32(len(strings.Fields("a"+s+"b"))))
		var flags byte
		if strings.EqualFold(s, string(unicode.ToLower(r))) {
			flags |= 1
		}
		if strings.EqualFold(s, string(unicode.ToUpper(r))) {
			flags |= 2
		}
		if strings.EqualFold(s, string(unicode.SimpleFold(r))) {
			flags |= 4
		}
		if strings.EqualFold("x"+s, "X"+string(unicode.SimpleFold(unicode.SimpleFold(r)))) {
			flags |= 8
		}
		fold.Write([]byte{flags})
	}
	return unicodeVector{
		Meta:              newMeta(),
		RuneMapsSHA256:    hex.EncodeToString(maps.Sum(nil)),
		PredicatesSHA256:  hex.EncodeToString(preds.Sum(nil)),
		StringMapsSHA256:  hex.EncodeToString(strs.Sum(nil)),
		FoldClosureSHA256: hex.EncodeToString(fold.Sum(nil)),
	}
}

// Meta identifies the toolchain behind a vector file.
type Meta struct {
	GoVersion      string `json:"go_version"`
	UnicodeVersion string `json:"unicode_version"`
}

func newMeta() Meta {
	return Meta{GoVersion: runtime.Version(), UnicodeVersion: unicode.Version}
}
