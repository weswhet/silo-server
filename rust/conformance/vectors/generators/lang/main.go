func modDir(path string) string {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", path).Output()
	if err != nil {
		panic(err)
	}
	return strings.TrimSpace(string(out))
}

func evalString(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.BasicLit:
		s, err := strconv.Unquote(e.Value)
		if err != nil {
			panic(err)
		}
		return s
	case *ast.BinaryExpr:
		return evalString(e.X) + evalString(e.Y)
	case *ast.ParenExpr:
		return evalString(e.X)
	}
	panic(fmt.Sprintf("not a string expression: %T", e))
}

func evalInt(e ast.Expr) int64 {
	switch e := e.(type) {
	case *ast.BasicLit:
		n, err := strconv.ParseInt(e.Value, 0, 64)
		if err != nil {
			panic(err)
		}
		return n
	case *ast.UnaryExpr:
		if e.Op == token.SUB {
			return -evalInt(e.X)
		}
	}
	panic(fmt.Sprintf("not an integer expression: %T", e))
}

func ints(lit *ast.CompositeLit) []int64 {
	out := make([]int64, 0, len(lit.Elts))
	for _, elt := range lit.Elts {
		out = append(out, evalInt(elt))
	}
	return out
}

// fromTo reads {From: x, To: y} elements, keyed by index, into a flat [from, to, from, to...] list.
func fromTo(lit *ast.CompositeLit) []int64 {
	var out []int64
	for _, elt := range lit.Elts {
		if kv, ok := elt.(*ast.KeyValueExpr); ok {
			elt = kv.Value
		}
		inner := elt.(*ast.CompositeLit)
		for _, f := range inner.Elts {
			out = append(out, evalInt(f.(*ast.KeyValueExpr).Value))
		}
	}
	return out
}

func rustBytes(s string) string {
	var b strings.Builder
	b.WriteString(`b"`)
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c >= 0x20 && c < 0x7f:
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, `\x%02x`, c)
		}
	}
	b.WriteString(`"`)
	return b.String()
}

func rustInts(name, ty string, values []int64) string {
	var b strings.Builder
	fmt.Fprintf(&b, "pub const %s: [%s; %d] = [", name, ty, len(values))
	for i, v := range values {
		if i%16 == 0 {
			b.WriteString("\n    ")
		} else {
			b.WriteByte(' ')
		}
		fmt.Fprintf(&b, "%d,", v)
	}
	b.WriteString("\n];\n")
	return b.String()
}

func writeTables() {
	path := filepath.Join(modDir("golang.org/x/text"), "internal/language/tables.go")
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		panic(err)
	}
	strs := map[string]string{}
	values := map[string]ast.Expr{}
	consts := map[string]int64{}
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range gen.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok || len(vs.Values) == 0 {
				continue
			}
			name := vs.Names[0].Name
			values[name] = vs.Values[0]
			switch v := vs.Values[0].(type) {
			case *ast.BasicLit:
				if v.Kind == token.STRING {
					strs[name] = evalString(v)
				} else if v.Kind == token.INT {
					consts[name] = evalInt(v)
				}
			case *ast.BinaryExpr:
				strs[name] = evalString(v)
			}
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by rust/conformance/vectors/generators/lang. DO NOT EDIT.\n")
	b.WriteString("//\n// Tables from golang.org/x/text/internal/language/tables.go, frozen at the module version in go.mod.\n\n")
	for _, name := range []struct{ goName, rust string }{
		{"lang", "LANG"}, {"altLangISO3", "ALT_LANG_ISO3"}, {"script", "SCRIPT"},
		{"regionISO", "REGION_ISO"}, {"altRegionISO3", "ALT_REGION_ISO3"},
	} {
		s, ok := strs[name.goName]
		if !ok {
			panic("missing string table " + name.goName)
		}
		fmt.Fprintf(&b, "pub const %s: &[u8] = %s;\n", name.rust, rustBytes(s))
	}
	for _, name := range []struct{ goName, rust, ty string }{
		{"langNoIndex", "LANG_NO_INDEX", "u8"}, {"altLangIndex", "ALT_LANG_INDEX", "u16"},
		{"AliasTypes", "ALIAS_TYPES", "u8"}, {"altRegionIDs", "ALT_REGION_IDS", "u16"},
		{"m49", "M49", "i16"}, {"m49Index", "M49_INDEX", "i16"}, {"fromM49", "FROM_M49", "u16"},
	} {
		lit, ok := values[name.goName].(*ast.CompositeLit)
		if !ok {
			panic("missing table " + name.goName)
		}
		b.WriteString(rustInts(name.rust, name.ty, ints(lit)))
	}
	for _, name := range []struct{ goName, rust string }{
		{"AliasMap", "ALIAS_MAP"}, {"regionOldMap", "REGION_OLD_MAP"},
	} {
		b.WriteString(rustInts(name.rust, "u16", fromTo(values[name.goName].(*ast.CompositeLit))))
	}

	variants := values["variantIndex"].(*ast.CompositeLit)
	type variant struct {
		name string
		id   int64
	}
	var list []variant
	for _, elt := range variants.Elts {
		kv := elt.(*ast.KeyValueExpr)
		list = append(list, variant{evalString(kv.Key), evalInt(kv.Value)})
	}
	sort.Slice(list, func(i, j int) bool { return list[i].name < list[j].name })
	b.WriteString("/// Sorted by name.\npub const VARIANT_INDEX: &[(&str, u8)] = &[\n")
	for _, v := range list {
		fmt.Fprintf(&b, "    (%q, %d),\n", v.name, v.id)
	}
	b.WriteString("];\n")

	for _, name := range []struct{ goName, rust, ty string }{
		{"nonCanonicalUnd", "NON_CANONICAL_UND", "u16"}, {"langNoIndexOffset", "LANG_NO_INDEX_OFFSET", "u16"},
		{"isoRegionOffset", "ISO_REGION_OFFSET", "u16"},
		{"_sh", "LANG_SH", "u16"}, {"_mo", "LANG_MO", "u16"}, {"_no", "LANG_NO", "u16"}, {"_nb", "LANG_NB", "u16"},
		{"_Latn", "SCRIPT_LATN", "u16"}, {"_Qaai", "SCRIPT_QAAI", "u16"}, {"_Zinh", "SCRIPT_ZINH", "u16"},
		{"_MD", "REGION_MD", "u16"},
	} {
		v, ok := consts[name.goName]
		if !ok {
			panic("missing const " + name.goName)
		}
		fmt.Fprintf(&b, "pub const %s: %s = %d;\n", name.rust, name.ty, v)
	}
	if err := os.WriteFile(tablesOut, b.Bytes(), 0o644); err != nil {
		panic(err)
	}
}

